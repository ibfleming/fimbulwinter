#!/usr/bin/env python3
"""Apply pending updates: one commit per mod (no AI).

  stage-dir  Write a directory with thunderstore.toml (all updates applied)
             and a copy of config/ -- the --repo-dir for the new-version
             harvest boot.
  apply      For each update, in toml order: bump its pin, add any newly
             required dependency, migrate its config files with
             config_diff.py (old harvest, new harvest, shipped), and commit
             `chore(deps): bump <mod> from <a> to <b>`. Writes a JSON +
             Markdown config report that the agent and the PR body use.

Usage:
  apply_updates.py stage-dir --evidence index.json --out DIR
  apply_updates.py apply --evidence index.json --old-harvest DIR
                   --new-harvest DIR --report-dir DIR [--no-commit]
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
from pathlib import Path

import config_diff
import tslib

TOML = tslib.REPO / "thunderstore.toml"


def bump(text: str, mod: str, old: str, new: str, extra: list[dict]) -> str:
    pat = re.compile(rf'^({re.escape(mod)}\s*=\s*)"{re.escape(old)}"', re.M)
    text, n = pat.subn(rf'\g<1>"{new}"', text)
    if n != 1:
        raise SystemExit(f"could not find {mod} = \"{old}\" in thunderstore.toml")
    for req in extra:
        if re.search(rf"^{re.escape(req['package'])}\s*=", text, re.M):
            continue
        line = f'{req["package"]} = "{req["version"]}"  # required by {mod}'
        text = re.sub(rf'^({re.escape(mod)}\s*=.*)$', rf"\1\n{line}", text, count=1, flags=re.M)
    return text


def ordered(index: dict) -> list[dict]:
    order = list(tslib.pinned_deps())
    return sorted(index.values(), key=lambda e: order.index(e["mod"]) if e["mod"] in order else 999)


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(tslib.REPO), *args], check=True,
                          capture_output=True, text=True).stdout


def cmd_stage_dir(a) -> int:
    index = json.loads(Path(a.evidence).read_text())
    text = TOML.read_text()
    for e in ordered(index):
        text = bump(text, e["mod"], e["current"], e["latest"], e["new_required"])
    out = Path(a.out)
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    (out / "thunderstore.toml").write_text(text)
    shutil.copytree(tslib.REPO / "config", out / "config")
    tslib.log(f"staged bumped toml in {out}")
    return 0


def cmd_apply(a) -> int:
    index = json.loads(Path(a.evidence).read_text())
    report_dir = Path(a.report_dir)
    report_dir.mkdir(parents=True, exist_ok=True)
    report, md = [], ["# Config migration", ""]
    shipped = tslib.REPO / "config"

    for e in ordered(index):
        mod = e["mod"]
        TOML.write_text(bump(TOML.read_text(), mod, e["current"], e["latest"], e["new_required"]))
        results = []
        for rel in e["configs"]:
            if not rel.endswith(".cfg") or "/" in rel:
                continue
            r = config_diff.diff_file(rel, shipped / rel, Path(a.new_harvest) / rel,
                                      Path(a.old_harvest) / rel)
            if "_render" in r and r["changes"]:
                (shipped / rel).write_bytes(config_diff.render(*r.pop("_render")))
            r.pop("_render", None)
            results.append(r)
        auto = sum(r["auto"] for r in results)
        review = sum(r["review"] for r in results)
        not_gen = [r["file"] for r in results if r["status"] == "not-generated"]
        report.append({"mod": mod, "from": e["current"], "to": e["latest"],
                       "side": e["side"], "configs": results, "auto": auto,
                       "review": review, "not_generated": not_gen})
        md += [f"## {mod} {e['current']} -> {e['latest']}", "",
               config_diff.to_md(results), ""]

        body = [f"Side: {e['side']}."]
        if results:
            body.append(f"Config: {auto} setting(s) migrated automatically, "
                        f"{review} flagged for review.")
        if not_gen:
            body.append("Not generated by a headless server (check in a client): "
                        + ", ".join(not_gen) + ".")
        if e["new_required"]:
            body.append("Adds newly required: " + ", ".join(
                f"{r['package']} {r['version']}" for r in e["new_required"]) + ".")
        if not a.no_commit:
            git("add", "thunderstore.toml", "config")
            git("commit", "-q", "-m", f"chore(deps): bump {mod} from {e['current']} to {e['latest']}",
                "-m", "\n".join(body))
        tslib.log(f"{mod}: {auto} auto, {review} review" + (f", not generated: {not_gen}" if not_gen else ""))

    (report_dir / "config-report.json").write_text(json.dumps(report, indent=2) + "\n")
    (report_dir / "config-report.md").write_text("\n".join(md))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("stage-dir")
    p.add_argument("--evidence", required=True)
    p.add_argument("--out", required=True)
    p = sub.add_parser("apply")
    p.add_argument("--evidence", required=True)
    p.add_argument("--old-harvest", required=True)
    p.add_argument("--new-harvest", required=True)
    p.add_argument("--report-dir", required=True)
    p.add_argument("--no-commit", action="store_true")
    a = ap.parse_args()
    return cmd_stage_dir(a) if a.cmd == "stage-dir" else cmd_apply(a)


if __name__ == "__main__":
    raise SystemExit(main())
